def build_handoff(case_id: str, vault_path: str | Path, hashes: Dict[str, Any],
                  out_dir: str | Path, *, box_name: str = "BlueTeamDynamic",
                  box_verified: bool = False, verify_note: str = "",
                  prerequisites: Optional[List[str]] = None) -> Handoff:
    """生成交接包（三个文件）。**只写文件，不执行任何东西。**"""
    vp = Path(vault_path)
    od = Path(out_dir)
    od.mkdir(parents=True, exist_ok=True)

    h = Handoff(
        case_id=case_id,
        box_name=box_name,
        vault_path=str(vp.parent),
        payload_name=vp.name,
        hashes=hashes or {},
        created=time.strftime("%Y-%m-%d %H:%M:%S"),
        out_dir=str(od),
        box_verified=bool(box_verified),
        verify_note=verify_note,
        prerequisites=prerequisites if prerequisites is not None else _default_prereqs(),
    )
    h.cmd_file = str(od / "run_dynamic_analysis.cmd")
    h.md_file = str(od / "HANDOFF.md")
    h.json_file = str(od / "handoff.json")

    # 批处理必须 CRLF + ASCII：cmd.exe 在中文 Windows 上按 936 代码页解析，
    # LF 行尾与 UTF-8 中文都可能导致行解析错位。
    cmd = render_dynamic_cmd(h)
    with open(h.cmd_file, "w", encoding="ascii", errors="replace", newline="\r\n") as fh:
        fh.write(cmd)
    Path(h.md_file).write_text(render_handoff_md(h), encoding="utf-8")
    Path(h.json_file).write_text(json.dumps(h.to_dict(), ensure_ascii=False, indent=2),
                                encoding="utf-8")
    return h


def _default_prereqs() -> List[str]:
    return [
        "先跑 `python -m sandbox.sandboxie --verify-net` 并确认**差分断网验证通过**"
        "（沙箱内连不出去 且 沙箱外连得出去；两个条件都要，只满足一个等于没验证）。",
        "优先在虚拟机快照上做。沙箱不是绝对保证，快照才是唯一的兜底。",
        "载荷镜像必须是只读的（本流程已设只读属性），且哈希与本单一致。",
        "确认这台机器上没有正在进行的业务操作会被沙箱资源占用影响。",
        "准备好记录：C2 的 IP:端口、落地的文件路径、持久化位置。",
    ]


# --------------------------------------------------------------------------- #
# 结构性保证：本模块没有执行能力
# --------------------------------------------------------------------------- #

def assert_no_execution(source: Optional[str] = None) -> List[str]:
    """用 AST 证明本模块**不存在**执行类调用。返回违规列表（空 = 通过）。

    为什么用 AST 而不是正则/文本搜索：文本搜索会被自己的文档字符串骗到
    （本文件的 docstring 里就写着 `subprocess`、`os.system` 这些词）。
    `forensics/containment.py` 的同类自检一开始就是文本搜索，因为这个原因假失败过。
    """
    src = source if source is not None else Path(__file__).read_text(encoding="utf-8")
    tree = ast.parse(src)
    bad: List[str] = []

    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            for a in node.names:
                if a.name.split(".")[0] in _FORBIDDEN_IMPORTS:
                    bad.append(f"第 {node.lineno} 行：import {a.name}")
        elif isinstance(node, ast.ImportFrom):
            if (node.module or "").split(".")[0] in _FORBIDDEN_IMPORTS:
                bad.append(f"第 {node.lineno} 行：from {node.module} import ...")
        elif isinstance(node, ast.Call):
            fn = node.func
            if isinstance(fn, ast.Attribute) and isinstance(fn.value, ast.Name):
                if (fn.value.id, fn.attr) in _FORBIDDEN_CALLS:
                    bad.append(f"第 {node.lineno} 行：{fn.value.id}.{fn.attr}()")
    return bad


