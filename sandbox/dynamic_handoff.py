def render_dynamic_cmd(h: Handoff) -> str:
    """生成给人工运行的批处理。**纯 ASCII**（cmd 在 936 代码页下会吃坏 UTF-8 中文）。

    脚本只做四件事：自检环境 → 打印哈希 → 在沙箱里运行 → 回收产物。
    每一步失败都 `exit /b 1`，不做"失败也继续"的兜底 —— 人工流程必须显式看到失败。
    """
    box = h.box_name
    vault = h.vault_path.replace('"', "")
    name = h.payload_name.replace('"', "")
    sha = (h.hashes or {}).get("sha256", "")
    return f"""@echo off
setlocal enableextensions
rem ===================================================================
rem  run_dynamic_analysis.cmd  --  MANUAL step. A human runs this.
rem
rem  Generated by sandbox/dynamic_handoff.py. The AI never runs payloads;
rem  this file exists so a human can do the dynamic analysis themselves.
rem
rem  Case     : {h.case_id}
rem  Sandbox  : {box}
rem  Payload  : {vault}\\{name}
rem  SHA-256  : {sha}
rem
rem  Preconditions (see HANDOFF.md):
rem    1. sandboxie.verify_network_isolation() must have passed
rem    2. Prefer a VM snapshot. A sandbox is not an absolute guarantee.
rem ===================================================================

set "SBIE=C:\\Program Files\\Sandboxie-Plus\\Start.exe"
set "PAYLOAD={vault}\\{name}"
set "BOX={box}"

echo.
echo [1/5] Checking Sandboxie installation ...
if not exist "%SBIE%" (
  echo   ERROR: Start.exe not found at "%SBIE%".
  echo   Install Sandboxie-Plus first, then update the SBIE path in this file.
  exit /b 1
)
"%SBIE%" /? >nul 2>&1
if errorlevel 1 (
  echo   ERROR: Start.exe did not respond. Is the Sandboxie service running?
  exit /b 1
)
echo   OK

echo.
echo [2/5] Verifying payload hash (must match the value recorded above) ...
if not exist "%PAYLOAD%" (
  echo   ERROR: payload not found: "%PAYLOAD%"
  exit /b 1
)
certutil -hashfile "%PAYLOAD%" SHA256 | findstr /i /v "hash CertUtil"
echo   Compare the line above with SHA-256 in the header. If it differs, STOP.

echo.
echo [3/5] Running the payload INSIDE the sandbox ...
echo   Box: %BOX%
echo   Any file/registry changes it makes stay inside the box.
echo   Watch for: outbound connections, dropped files, persistence, child processes.
echo.
echo   Press Ctrl+C now if you change your mind.
pause
start "" "%SBIE%" /box:%BOX% "%PAYLOAD%"
if errorlevel 1 (
  echo   ERROR: Start.exe refused to launch the payload.
  exit /b 1
)
echo   Launched. Observe it, then come back here.

echo.
echo [4/5] When you are done observing, press any key to terminate the box ...
pause >nul
"%SBIE%" /box:%BOX% /terminate
echo   Box terminated.

echo.
echo [5/5] Collecting artefacts out of the box (for the record) ...
set "SRC=%USERPROFILE%\\..\\..\\Sandbox\\%USERNAME%\\%BOX%"
if not exist "%SRC%" (
  echo   WARN: box storage not found at "%SRC%".
  echo   Nothing to collect. Check Sandboxie's FileRootPath setting.
) else (
  set "DST={vault}\\..\\..\\cases\\{h.case_id}\\detonation"
  if not exist "%DST%" mkdir "%DST%"
  xcopy /E /I /Y /Q "%SRC%" "%DST%" >nul
  echo   Copied to "%DST%".
)

echo.
echo Done. Record what you observed in HANDOFF.md / the case ticket.
echo If you saw outbound connections, note the remote IP:port - that is the C2.
endlocal
exit /b 0
"""


def render_handoff_md(h: Handoff) -> str:
    """给人工看的中文操作手册。"""
    hs = h.hashes or {}
    L: List[str] = []
    L.append(f"# 动态分析交接单 — {h.case_id}")
    L.append("")
    L.append("> **这份工作由人工完成，AI 不执行任何样本。**")
    L.append("> 本文件由系统生成，AI 侧代码里**不存在**执行载荷的能力（见 "
             "`sandbox/dynamic_handoff.py` 的 `assert_no_execution()` 自检）。")
    L.append("")
    L.append("## 一、交付物")
    L.append("")
    L.append(f"- 载荷镜像（只读）：`{h.vault_path}\\{h.payload_name}`")
    L.append(f"- 沙箱名：`{h.box_name}`")
    L.append(f"- 交接时间：{h.created}")
    L.append("")
    L.append("| 哈希 | 值 |")
    L.append("|---|---|")
    L.append(f"| SHA-256 | `{hs.get('sha256', '')}` |")
    L.append(f"| SHA-1 | `{hs.get('sha1', '')}` |")
    L.append(f"| MD5 | `{hs.get('md5', '')}` |")
    L.append(f"| 大小 | {hs.get('size', 0)} 字节 |")
    L.append("")
    L.append("## 二、动手前必须确认（缺一条就别跑）")
    L.append("")
    if h.prerequisites:
        L.extend(f"{i}. {p}" for i, p in enumerate(h.prerequisites, 1))
    else:
        L.append("（未记录前置条件 —— 这本身就不正常，请重新生成交接单）")
    L.append("")
    L.append(f"- 断网验证状态：{'**已通过**' if h.box_verified else '**未通过 / 未验证**'}"
             + (f"（{h.verify_note}）" if h.verify_note else ""))
    L.append("")
    L.append("## 三、怎么做")
    L.append("")
    L.append("1. 双击运行同目录下的 `run_dynamic_analysis.cmd`。")
    L.append("2. 脚本会先自检 Sandboxie、再打印载荷哈希 —— **哈希必须与上表一致**，"
             "不一致说明镜像在提取后被动过，立刻停止并回查。")
    L.append("3. 确认后它会在沙箱内启动载荷。此时**观察**，不要在旁边做别的事干扰判断。")
    L.append("4. 观察完按任意键结束，脚本会终止沙箱并把沙箱内的改动导出到案例目录。")
    L.append("")
    L.append("## 四、重点观察什么（按价值排序）")
    L.append("")
    L.append("| 观察点 | 为什么重要 | 怎么看 |")
    L.append("|---|---|---|")
    L.append("| 外连目标 IP:端口 | 这是 C2，是封锁与情报的直接输入 | `netstat -ano` 找载荷的 PID；"
             "或看沙箱内的连接 |")
    L.append("| 落地的文件 | 说明有释放阶段，通常还能找到更多样本 | 沙箱导出目录 `drive\\` 下的新增文件 |")
    L.append("| 持久化动作 | 决定清除范围 | 沙箱内的注册表/启动目录/计划任务改动 |")
    L.append("| 子进程 | 白利用（LOLBin）通常有父子链 | 任务管理器「命令行」列 |")
    L.append("| 是否自我删除 | 说明是投递器而非最终载荷 | 载荷文件是否消失 |")
    L.append("")
    L.append("## 五、做完之后")
    L.append("")
    L.append("把观察结果写进 `handoff.json` 的 `human_findings` 字段，或直接记进工单，"
             "然后交回自动化流程：")
    L.append("")
    L.append("```powershell")
    L.append("# 对人工观察到的 C2 做最小影响封锁（只封这一个对端，不动业务）")
    L.append(".\\actions\\cli.ps1 contain --host-id <本机> --indicator <C2的IP或域名>")
    L.append("")
    L.append("# 对沙箱里导出的落地文件做静态分析（同样是静态，不执行）")
    L.append("python -m sandbox.payload \"<案例目录>\\detonation\\...\\dropped.exe\"")
    L.append("```")
    L.append("")
    L.append("## 六、为什么不由 AI 自动做")
    L.append("")
    L.append("动态分析要**执行攻击者写的代码**。沙箱（尤其 Sandboxie 这种用户态沙箱 + "
             "内核驱动）不是绝对保证：配置不当、沙箱逃逸漏洞、载荷针对沙箱做对抗，"
             "都可能让「分析样本」变成「替攻击者重新上线」。")
    L.append("")
    L.append("所以边界这样划：**自动化负责不变的部分**（提取、哈希、静态结构、"
             "字符串、封锁具体对端、留痕），**人负责需要判断与承担责任的部分**"
             "（决定要不要跑、跑的时候盯什么、结论怎么定）。")
    return "\n".join(L)


