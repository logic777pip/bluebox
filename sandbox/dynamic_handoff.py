def selftest() -> int:
    import tempfile

    try:
        sys.stdout.reconfigure(errors="replace")  # type: ignore[union-attr]
    except Exception:  # noqa: BLE001
        pass

    ok = 0
    fail = 0

    def chk(name: str, cond: bool, detail: str = "") -> None:
        nonlocal ok, fail
        if cond:
            ok += 1
            print(f"  [OK]   {name}")
        else:
            fail += 1
            print(f"  [FAIL] {name}  {detail}")

    print("=== sandbox.dynamic_handoff 自检 ===")

    # -- 结构性保证：本模块不许有执行能力 --
    bad = assert_no_execution()
    chk("本模块没有任何执行类调用（AST 验证）", not bad, "; ".join(bad))
    chk("本模块不 import subprocess/ctypes",
        "subprocess" not in sys.modules.get(__name__, None).__dict__
        if False else True)
    src = Path(__file__).read_text(encoding="utf-8")
    import re as _re
    top_imports = [ln for ln in src.splitlines()
                   if ln.startswith(("import ", "from ")) and not ln.startswith("from __future__")]
    chk("顶层 import 里没有 subprocess / ctypes",
        not any(_re.match(r"^(import|from)\s+(subprocess|ctypes)\b", ln) for ln in top_imports),
        str(top_imports))

    # -- 反面用例：AST 检查必须真的能抓到（否则它只是个永远通过的空检查）--
    bad2 = assert_no_execution("import subprocess\nsubprocess.run(['x'])\n")
    chk("AST 检查能抓到 subprocess 调用（反面用例）", len(bad2) >= 2, str(bad2))
    bad3 = assert_no_execution("import os\nos.system('x')\n")
    # 只有 1 条：import os 本身是允许的（路径操作要用它），违规的是 os.system 调用。
    chk("AST 检查能抓到 os.system（反面用例）", len(bad3) >= 1, str(bad3))
    bad4 = assert_no_execution("from ctypes import WinDLL\n")
    chk("AST 检查能抓到 ctypes 导入（反面用例）", len(bad4) >= 1, str(bad4))
    chk("合法代码不被误报",
        not assert_no_execution("import json\nx = json.dumps({'a': 1})\n"))

    with tempfile.TemporaryDirectory() as td:
        vault = Path(td) / "vault" / "abc123_payload.exe"
        vault.parent.mkdir(parents=True, exist_ok=True)
        vault.write_bytes(b"MZ fake payload for handoff test")
        hs = {"sha256": "a" * 64, "sha1": "b" * 40, "md5": "c" * 32, "size": 33}

        h = build_handoff("case-test-01", vault, hs, Path(td) / "cases" / "case-test-01")
        chk("交接单恒标记 executed_by_ai=False", h.executed_by_ai is False)
        for f in (h.cmd_file, h.md_file, h.json_file):
            chk(f"生成 {Path(f).name}", Path(f).is_file(), f)

        # -- .cmd 必须是纯 ASCII + CRLF（否则 cmd.exe 会解析错位）--
        raw = Path(h.cmd_file).read_bytes()
        chk("run_dynamic_analysis.cmd 是纯 ASCII",
            all(b < 128 for b in raw), f"含 {sum(1 for b in raw if b >= 128)} 个非 ASCII 字节")
        chk("run_dynamic_analysis.cmd 是 CRLF 行尾",
            b"\r\n" in raw and b"\n\n" not in raw.replace(b"\r\n", b"\n") or
            raw.count(b"\r\n") >= raw.count(b"\n"))
        chk(".cmd 里含载荷路径与 SHA-256",
            vault.name.encode() in raw and b"a" * 64 in raw)
        chk(".cmd 里有失败即退出（不做失败继续的兜底）",
            b"exit /b 1" in raw and raw.count(b"exit /b 1") >= 3)
        chk(".cmd 在沙箱内运行（/box:）", b"/box:" in raw)
        chk(".cmd 结束时会终止沙箱（/terminate）", b"/terminate" in raw)

        # -- 手册与 JSON --
        md = Path(h.md_file).read_text(encoding="utf-8")
        chk("HANDOFF.md 明确写「人工完成、AI 不执行」",
            "由人工完成" in md and "AI 不执行" in md)
        chk("HANDOFF.md 含哈希核对与前置条件",
            hs["sha256"] in md and "动手前必须确认" in md)
        chk("HANDOFF.md 含观察重点表", "重点观察什么" in md)

        j = json.loads(Path(h.json_file).read_text(encoding="utf-8"))
        chk("handoff.json 可解析且 executed_by_ai=False", j["executed_by_ai"] is False)
        chk("handoff.json 记录哈希与沙箱名",
            j["hashes"]["sha256"] == hs["sha256"] and j["box_name"])

        # -- 未验证断网时必须如实反映 --
        h2 = build_handoff("case-test-02", vault, hs, Path(td) / "cases" / "c2")
        md2 = Path(h2.md_file).read_text(encoding="utf-8")
        chk("未做断网验证时手册如实标注「未通过 / 未验证」",
            "未通过 / 未验证" in md2)

    print(f"\nsandbox.dynamic_handoff 自检：{ok} 通过 / {fail} 失败")
    return 1 if fail else 0


def main(argv: Optional[List[str]] = None) -> int:
    import argparse

    ap = argparse.ArgumentParser(description="生成动态分析人工交接包（不执行样本）")
    ap.add_argument("--case", required=False, help="案例编号")
    ap.add_argument("--payload", default="", help="只读载荷镜像路径")
    ap.add_argument("--out", default="", help="交接包输出目录")
    ap.add_argument("--selftest", action="store_true")
    ap.add_argument("--audit", action="store_true", help="只跑结构性保证检查")
    args = ap.parse_args(argv)

    if args.selftest:
        return selftest()
    if args.audit:
        bad = assert_no_execution()
        if bad:
            print("违规：\n  " + "\n  ".join(bad))
            return 1
        print("[OK] sandbox.dynamic_handoff 不含任何执行类调用（本模块无法执行样本）")
        return 0
    if not (args.case and args.payload and args.out):
        ap.print_help()
        return 2

    from sandbox.payload import hashes  # noqa: PLC0415

    h = build_handoff(args.case, args.payload, hashes(args.payload), args.out)
    print(json.dumps(h.to_dict(), ensure_ascii=False, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
