#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""sandbox/dynamic_handoff.py — 把**动态分析交接给人工**，本模块自己绝不执行样本。

为什么单独一个模块
------------------

需求是「禁止 AI 进行动态分析，动态分析由人工进行」。这种约束如果只写在配置里
（`execute_enabled: false`）或文档里，是**可以被一行改动绕过的**：哪天有人把它改成
true，AI 就具备引爆样本的能力了。所以这里换一种做法：

    **让 AI 侧根本不存在"执行样本"的代码路径。**

本模块的全部职责就是**生成文本文件**：一个给人工双击的 `run_dynamic_analysis.cmd`、
一份中文操作手册 `HANDOFF.md`、一条机器可读的交接记录 `handoff.json`。
它自身没有任何 `subprocess` / `os.system` / `os.popen` 调用 —— 这不是靠"我没写"，
而是靠 `assert_no_execution()` 用 AST 逐节点验证并在自检里跑：

    * 出现 `subprocess`、`os.system`、`os.popen`、`os.spawn*`、`ctypes` 载入等
      任何执行类原语 → 自检直接失败。

也就是说，能力边界是**结构性的**，不是策略性的。

生成物为什么是英文 .cmd + 中文 .md
-----------------------------------

`cmd.exe` 在中文 Windows 上按 OEM 代码页（936）解析批处理文件，UTF-8 中文会变乱码，
进而可能让 `if` / `goto` 的行解析错位。项目里 `.ps1` 已经因为同类原因规定纯 ASCII。
所以 `.cmd` 一律英文；中文说明写进 UTF-8 的 `HANDOFF.md`（编辑器读，不经 cmd 解析）。

人工要做什么（也写在生成的手册里）
----------------------------------

1. 先确认 `sandboxie.verify_network_isolation()` 的**差分断网验证**通过
   （沙箱内连不出去 且 沙箱外连得出去，两个条件都要）；
2. 最好在快照/虚拟机里做，沙箱不是绝对保证；
3. 运行 `run_dynamic_analysis.cmd`，观察手册里列出的行为点；
4. 把观察结果回填到 `handoff.json` 的 `human_findings` 字段（或记进工单）。
"""

from __future__ import annotations

import ast
import hashlib
import json
import os
import sys
import time
from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import Any, Dict, List, Optional

PROJECT_ROOT = Path(__file__).resolve().parents[1]
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

__all__ = ["Handoff", "build_handoff", "render_handoff_md",
           "render_dynamic_cmd", "assert_no_execution", "selftest"]

#: 本模块**禁止出现**的调用（(模块名, 属性名)）。AST 自检按这个表查。
_FORBIDDEN_CALLS = {
    ("subprocess", "run"), ("subprocess", "Popen"), ("subprocess", "call"),
    ("subprocess", "check_output"), ("subprocess", "check_call"),
    ("os", "system"), ("os", "popen"), ("os", "spawnl"), ("os", "spawnv"),
    ("os", "execv"), ("os", "execve"), ("os", "startfile"),
    ("ctypes", "CDLL"), ("ctypes", "WinDLL"), ("ctypes", "windll"),
}

#: 本模块**禁止 import** 的执行类模块
_FORBIDDEN_IMPORTS = {"subprocess", "ctypes", "shlex", "asyncio"}


@dataclass
class Handoff:
    """一次「交给人工做动态分析」的记录。"""

    case_id: str = ""
    box_name: str = "BlueTeamDynamic"
    vault_path: str = ""
    payload_name: str = ""
    hashes: Dict[str, Any] = field(default_factory=dict)
    created: str = ""
    out_dir: str = ""
    cmd_file: str = ""
    md_file: str = ""
    json_file: str = ""
    #: **恒为 False**：动态分析不由 AI 执行。留这个字段是为了让下游（报告/审计）
    #: 有一个可以断言的事实，而不是靠"读文档知道"。
    executed_by_ai: bool = False
    box_verified: bool = False
    verify_note: str = ""
    prerequisites: List[str] = field(default_factory=list)

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


